/** 一枚を、そのジャンルの眼で読んだ一行 */
export function lensLine(card: Card, lens: Lens): string {
  if (card.suit) {
    const s = SUITS.find((x) => x.key === card.suit)!;
    return (RANK_STAGE[card.rank!] ?? "") + s.lens[lens];
  }
  const m = MAJOR_LENS[card.n];
  return m ? (m[lens] ?? m.life) : "";
}

/* ---------- 札を引く（引いた札は必ず本文に効く） ---------- */
export type Drawn = { card: Card; rev: boolean };
export function drawFromPicks(picks: number[], seedStr: string): Drawn[] {
  // 利用者が選んだ位置そのものを種にするので、選ぶ手間が結果に直結する
  return picks.map((p, i) => {
    const h = hash32(`${seedStr}|${p}|${i}`);
    return { card: DECK[h % DECK.length], rev: (h >>> 9) % 100 < 38 };
  });
}
function hash32(s: string): number {
  let h = 2166136261;
  for (const c of s) { h ^= c.charCodeAt(0); h = Math.imul(h, 16777619); }
  return Math.abs(h);
}
